import { DEFAULT_AGENT_WIKI_FOLDER } from "../../constants";
import { buildWikiSchemaGuidance } from "../wiki/wiki-note-schema";

export function buildWikiExecutionDraftRequestContext(): string {
  return [
    "执行模式：上一个 assistant 回复已经给出了《Wiki 维护计划》。",
    "这一次不要重写维护计划，而是把那份计划推进成一个可确认的单条写入草稿。",
    "",
    "执行要求：",
    "- 只选择本轮最值得先落的一项动作。",
    "- 如果已有明确承接目标，优先更新已有 Wiki 或 Index；不要平行再造近名条目。",
    "- 只有目标确实不存在、且计划明确建议新建时，才创建新 Wiki。",
    "- 最多输出一个 sidet-action 块；在它前面只用 1 到 3 句说明为什么先做这一项。",
    "- 直接输出这个 sidet-action；不要先问用户是否确认，卡片本身就是确认入口。",
    `- 如果目标在 ${DEFAULT_AGENT_WIKI_FOLDER} 下，内容必须是最终可写入的标准 Wiki Markdown：真实 YAML frontmatter、唯一标题、对应正文骨架。`,
    "- 如果这次更适合只补 Index，就只输出 Index 的动作，不顺手再造别的卡片。",
    "- 如果计划判断本轮不该写入，直接解释原因，不要输出 sidet-action。",
    "- 不要再输出“# Wiki 维护计划”或多方案清单。"
  ].join("\n");
}

export function buildWikiMaintenancePlanPrompt(sourceLines: string[]): string {
  return [
    "你是 Sidet 的 Wiki 管家。请先生成 Wiki 维护计划，不要直接写最终 Wiki 正文，也不要声称已经修改文件。",
    "",
    ...sourceLines,
    "",
    `目标：让 ${DEFAULT_AGENT_WIKI_FOLDER} 成为长期综合层，由你判断应该新建、更新、合并、补链、跳过，或建议生成 Skill。`,
    "",
    "判断要求：",
    "- 优先维护已有 Wiki；不要因为有素材就新建孤岛。",
    "- 如果已经命中同名或近名 Wiki，优先判断更新、合并、区分或替换，不要平行再造。",
    "- 只保留能帮助下一次判断的高密度内容。",
    "- 原始笔记和对话是来源，不要复制过程材料。",
    "- 写文件、更新小节、合并或删除最终都由用户在写入卡片上确认；生成计划时不要额外向用户要确认。",
    "- 如果信息不足，列出需要用户确认的边界。",
    "- 如果涉及结构导航，优先考虑概念页，而不是把所有正文堆进一张知识卡。",
    "- 先判断这次更适合：保持知识卡、新建知识卡、升级概念页、拆出详页，还是只补顶层路由页。",
    "- 第一阶段只在已识别知识库自己的根目录内判断和检索，不跨目录聚合。",
    "- `Index.md` 只负责主题入口、先读顺序和跨主题导航，不承接长正文。",
    ...buildWikiSchemaGuidance(),
    "",
    "请按以下 Markdown 结构输出：",
    "",
    "# Wiki 维护计划",
    "",
    "## 用户需求与边界",
    "- 用 1-3 条概括本次要整理什么，以及不能越过什么边界。",
    "",
    "## 建议动作",
    "- 用最短清单说明本轮建议做什么；如果不建议写入，也直接说明。",
    "",
    "## 形态判断",
    "- 对每个值得进入 Wiki 的主题，明确写出：保持知识卡 / 新建知识卡 / 升级概念页 / 拆出详页 / 只补 Index。",
    "- 每条都说明是什么信号让你这样判断，例如：单一判断、子题开始增多、正文已经过厚、需要顶层路由等。",
    "",
    "## 新建",
    "- 只列真正需要新建的 Wiki 条目，区分知识卡、概念页还是详页，并给出建议标题、建议路径、建议 sidet_type 和理由；如果更适合只补 Index，不要在这里造新卡。",
    "",
    "## 更新",
    "- 列出更适合补充的已有 Wiki 或候选目标，并说明应补哪一类内容，以及保持知识卡、升级概念页、拆出详页，还是只补 Index。",
    "",
    "## 合并 / 去重",
    "- 标出可能重复、可合并或不该制造孤岛的内容。",
    "",
    "## 补链",
    "- 建议需要补的 [[双链]]、来源链接、父子关系或相关概念链接。",
    "",
    "## 跳过",
    "- 列出不值得进入 Wiki 的过程材料、临时判断或低价值内容。",
    "",
    "## 可选 Skill",
    "- 只有当本轮形成可复用操作协议时才建议生成；否则写“无”。",
    "",
    "## 需要用户确认",
    "- 列出执行前必须确认的目标、边界或风险。"
  ].join("\n");
}
